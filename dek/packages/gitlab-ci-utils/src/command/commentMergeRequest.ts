import { Gitlab, MergeRequestNoteSchema } from "@gitbeaker/rest";

export interface CommentMergeRequestCommandOptions {
  projectId: string | number;
  mrIid: number;
  gitlabHost: string;
  gitlabToken: string;
  title: string;
  body: string;
}

const footer = "generated by fair bot";

const noteExists = (title: string) => (notes: MergeRequestNoteSchema[]) =>
  notes.find((note) => note.body.includes(title) && note.body.includes(footer));

export const commentMergeRequest: (
  options: CommentMergeRequestCommandOptions,
) => void = async ({
  projectId,
  mrIid,
  gitlabHost,
  gitlabToken,
  title,
  body,
}) => {
  const api = new Gitlab({ token: gitlabToken, host: gitlabHost });

  const note = await api.MergeRequestNotes.all(projectId, mrIid).then(
    noteExists(title),
  );

  const noteFullBody = `## ${title}
        
${body}
        
${footer}`;

  if (note === undefined) {
    console.log("didn't find note. Create new.");
    console.log(noteFullBody);

    await api.MergeRequestNotes.create(projectId, mrIid, noteFullBody)
      .then(() => {
        console.log("successful creating note");
      })
      .catch(() => {
        console.log("failed creating note");
      });
  } else {
    console.log("found note. Finish.");
  }
};
